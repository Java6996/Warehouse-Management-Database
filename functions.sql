CREATE DEFINER=`root`@`localhost` FUNCTION `fn_estado_stock_producto`(p_id_producto INT) RETURNS varchar(50) CHARSET utf8mb4
    READS SQL DATA
BEGIN
    DECLARE v_stock INT;
    DECLARE v_estado VARCHAR(50);
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET v_estado = 'ERROR: producto inexistente';
    SELECT stock INTO v_stock FROM producto WHERE id = p_id_producto;
    IF v_estado IS NULL THEN SET v_estado = CASE
            WHEN v_stock = 0 THEN 'VACIO'
            WHEN v_stock < 20 THEN 'BAJO'
            ELSE 'NORMAL'
        END;
    END IF;
    RETURN v_estado;
END ;;
